import AppKit

/// Polls `NSPasteboard.general.changeCount`; macOS has no change notification.
@MainActor
final class PasteboardMonitor {
    /// Written alongside our own pastes so we don't re-capture them.
    static let ownWriteType = NSPasteboard.PasteboardType("com.omid.clipstack.own")

    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        ownWriteType,
    ]

    /// Larger images (e.g. uncompressed TIFFs of huge screenshots) are skipped.
    static let maxImageBytes = 40 * 1024 * 1024

    private let pasteboard = NSPasteboard.general
    private let store: ClipStore
    private var lastChangeCount: Int
    private var timer: Timer?

    init(store: ClipStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start(interval: TimeInterval = 0.5) {
        timer?.invalidate()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = interval / 2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard !UserDefaults.standard.bool(forKey: Prefs.capturePaused) else { return }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.ignoredTypes.contains) else { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Prefs.ignoredBundleIDs.contains(app) { return }
        guard let clip = read() else { return }
        store.insert(clip)
    }

    private func read() -> CapturedClip? {
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // Order matters: a copied file also carries a string, and a copied URL a string too.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return CapturedClip(kind: .file, filePaths: urls.map(\.path), sourceAppBundleID: source)
        }
        // Raw bytes only; any TIFF→PNG conversion happens off the main thread in ClipStore.
        if let type = pasteboard.availableType(from: [.png, .tiff]), let data = pasteboard.data(forType: type) {
            guard data.count <= Self.maxImageBytes else { return nil }
            return CapturedClip(kind: .image, imageData: data, sourceAppBundleID: source)
        }
        if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !string.isEmpty {
            if let url = URL(string: string), let scheme = url.scheme, ["http", "https"].contains(scheme),
               !string.contains(where: \.isWhitespace) {
                return CapturedClip(kind: .url, urlString: string, sourceAppBundleID: source)
            }
            return CapturedClip(kind: .text, text: string, sourceAppBundleID: source)
        }
        return nil
    }
}
